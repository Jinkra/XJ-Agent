// Headless check of the pet renderer (src/ui/pet-rig.js) in Edge: idle, tap, talk, drag, dock.
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require('playwright');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'test-results', 'live2d', 'pet');
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.json': 'application/json', '.png': 'image/png', '.css': 'text/css' };
(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 300, height: 450 }, deviceScaleFactor: 2 });
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.route('http://l2d.local/**', route => {
    const rel = decodeURIComponent(new URL(route.request().url()).pathname).replace(/^\/+/, '');
    const file = path.join(ROOT, rel);
    if (!fs.existsSync(file)) return route.fulfill({ status: 404, body: 'missing' });
    return route.fulfill({ status: 200, body: fs.readFileSync(file), headers: { 'content-type': MIME[path.extname(file)] || 'application/octet-stream' } });
  });
  await page.goto('http://l2d.local/live2d/build/pet-harness.html');
  await page.waitForFunction(() => document.querySelector('#rig').dataset.modelReady || document.querySelector('#rig').dataset.modelError, null, { timeout: 20000 });
  const err = await page.evaluate(() => document.querySelector('#rig').dataset.modelError);
  if (err) throw new Error(err);
  const shot = name => page.screenshot({ path: path.join(OUT, `${name}.png`), omitBackground: true });
  await page.waitForTimeout(600); await shot('idle_a');
  await page.waitForTimeout(1300); await shot('idle_b');
  const p1 = await page.evaluate(() => document.querySelector('#rig').dataset.params);
  await page.mouse.move(260, 120); await page.waitForTimeout(700); await shot('look_cursor');
  await page.evaluate(() => triggerPetInteraction()); await page.waitForTimeout(330); await shot('tap');
  await page.waitForTimeout(1200);
  await page.evaluate(() => petReact('completed')); await page.waitForTimeout(250); await shot('happy_talk');
  await page.waitForTimeout(1800);
  await page.evaluate(() => { document.body.classList.add('approval'); petTalk(1200); }); await page.waitForTimeout(400); await shot('approval');
  await page.evaluate(() => document.body.classList.remove('approval'));
  await page.evaluate(() => updatePetPose({ edge: 'free', dragging: true, vx: 1800, vy: 0, shakeSpeed: 0 }));
  await page.waitForTimeout(260); await shot('drag_right');
  await page.evaluate(() => updatePetPose({ edge: 'free', dragging: true, vx: -1800, vy: 300, shakeSpeed: 0 }));
  await page.waitForTimeout(260); await shot('drag_left');
  await page.evaluate(() => updatePetPose({ edge: 'free', dragging: false, vx: 0, vy: 0, shakeSpeed: 0 }));
  await page.waitForTimeout(180); await shot('drag_release');
  await page.evaluate(() => updatePetPose({ edge: 'bottom', dragging: false, vx: 0, vy: 0, shakeSpeed: 0 }));
  await page.waitForTimeout(500); await shot('dock_bottom');
  await page.evaluate(() => updatePetPose({ edge: 'free', dragging: false, vx: 0, vy: 0, shakeSpeed: 0 }));
  await page.waitForTimeout(600);
  const bottom = await page.evaluate(() => window.__petRig.paintedBottom());
  const p2 = await page.evaluate(() => document.querySelector('#rig').dataset.params);
  fs.writeFileSync(path.join(OUT, 'result.json'), JSON.stringify({ errors, bottom, p1, p2 }, null, 2));
  await browser.close();
  console.log(JSON.stringify({ errors, bottom, p1, p2 }));
})().catch(e => { console.error(e); process.exitCode = 1; });
